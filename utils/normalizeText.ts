export function normalizeText<T>(value: T): T {
  if (typeof value === 'string') {
    let next = value;
    for (const [bad, good] of REPLACEMENTS) {
      next = next.split(bad).join(good);
    }
    next = next.replace(/\{lunar\.getDayInChinese\(\)\}/g, '').replace(/\s{2,}/g, ' ').trim();
    return next as T;
  }

  if (Array.isArray(value)) {
    return value.map((item) => normalizeText(item)) as T;
  }

  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>).map(([key, item]) => [key, normalizeText(item)])
    ) as T;
  }

  return value;
}
